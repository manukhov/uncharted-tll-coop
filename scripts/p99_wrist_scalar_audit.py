def require(condition, message):
    if not condition:
        raise ValueError(message)


def _finite(values):
    values = tuple(float(x) for x in values)
    require(all(math.isfinite(x) for x in values), "nonfinite scalar input")
    return values


def quaternion(value):
    """Validate rather than silently normalize a supplied or authored Q."""
    q = _finite(value)
    require(len(q) == 4 and abs(sum(x*x for x in q)-1) < 1e-3,
            "expected finite unit quaternion xyzw")
    return q


def dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def unit(v):
    length = math.sqrt(dot(v, v))
    require(length > 0, "degenerate vector/quaternion")
    return tuple(x/length for x in v)


def conjugate(q):
    return (-q[0], -q[1], -q[2], q[3])


def multiply(a, b):
    """Hamilton a*b, xyzw. Native 129 shuffle products resolve to this order."""
    x,y,z,w = a
    X,Y,Z,W = b
    return (w*X+x*W+y*Z-z*Y, w*Y-x*Z+y*W+z*X,
            w*Z+x*Y-y*X+z*W, w*W-x*X-y*Y-z*Z)


def basis(q):
    """Native rows are world-space local axes (columns in column-vector math)."""
    x,y,z,w = quaternion(q)
    return ((1-2*(y*y+z*z),2*(x*y+w*z),2*(x*z-w*y)),
            (2*(x*y-w*z),1-2*(x*x+z*z),2*(y*z+w*x)),
            (2*(x*z+w*y),2*(y*z-w*x),1-2*(x*x+y*y)))


def _axis(axis):
    require(type(axis) is int and axis in (0,1,2), "basis axis must be 0..2")
    return axis


def rotate_vector(q, v):
    rows = basis(q)
    return tuple(sum(v[k]*rows[k][j] for k in range(3)) for j in range(3))


def wrap_degrees(angle_radians):
    """Native strict wrap endpoints: both -PI and +PI remain unchanged."""
    angle, = _finite((angle_radians,))
    angle = math.fmod(angle, TAU)
    if angle < -PI:
        angle += TAU
    elif angle > PI:
        angle -= TAU
    return angle * RAD_TO_DEG


def signed_twist_degrees(local_q, reference_q, axis):
    """Approximate custom129 math including its non-generic swing fallback."""
    q, reference = quaternion(local_q), quaternion(reference_q)
    axis = _axis(axis)
    if dot(reference, q) < 0:
        q = tuple(-x for x in q)
    a, b = unit(basis(reference)[axis]), unit(basis(q)[axis])
    cosine = dot(a, b)
    swing = (0.,0.,0.,1.)
    if cosine < SWING_DOT_LIMIT:
        cross = (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2],
                 a[0]*b[1]-a[1]*b[0])
        length2 = dot(cross, cross)
        length = math.sqrt(length2) if length2 >= MIN_NORMAL else 0.
        if length > SWING_CROSS_LIMIT:
            scale = math.sqrt(max(0., .5-.5*cosine))/length
            swing = tuple(x*scale for x in cross)+(math.sqrt(max(0.,.5+.5*cosine)),)
        elif cosine < 0:
            # 141A9571C/20/24 unpackh(zero,zero), unpackh(one,zero),
            # unpackh(previous two) gives [0,1,0,0], not [0,0,1,0].
            swing = (0.,1.,0.,0.)
    residual = unit(multiply(multiply(conjugate(reference),conjugate(swing)),q))
    length2 = dot(residual[:3],residual[:3])
    length = math.sqrt(length2) if length2 >= MIN_NORMAL else 0.
    signed_axis = unit(residual[:3]) if length2 > AXIS_NORM2_LIMIT else (1.,0.,0.)
    angle = 2*math.atan2(length,residual[3])
    return wrap_degrees(-angle if signed_axis[axis] < 0 else angle)


def angular_falloff(degrees, start, end):
    """128 linear-clamp or hard-step; equality belongs to the 1 side."""
    degrees,start,end = _finite((degrees,start,end))
    if end <= start:
        return 1. if degrees <= start else 0.
    return min(1., max(0., 1.-(degrees-start)/(end-start)))


def angular_weight(local_q, target_q, axis, start, end, *,
                   reference_q=None, reference_axis=None, optional_degrees=None):
    """Approximate custom128. Optional absent means identity, not zero input Q."""
    current = unit(basis(local_q)[_axis(axis)])
    target = unit(basis(target_q)[axis])
    if optional_degrees is not None:
        require(reference_q is not None and reference_axis is not None,
                "optional twist requires authored reference Q and axis")
        degrees, = _finite((optional_degrees,))
        direction = unit(basis(reference_q)[_axis(reference_axis)])
        half = degrees*DEG_TO_RAD*.5
        twist = unit(tuple(x*math.sin(half) for x in direction)+(math.cos(half),))
        target = rotate_vector(twist,target)
    cosine = dot(current,target)
    require(-1.-1e-12 <= cosine <= 1.+1e-12,
            "acos outside analytic domain (native has no input clamp)")
    angle = math.acos(min(1.,max(-1.,cosine))) * RAD_TO_DEG
    return angular_falloff(angle,start,end)


@dataclass(frozen=True)
class ScalarDescriptor:
    opcode: int
    file_offset: int
    raw: bytes

    @property
    def target_q(self):
        return struct.unpack_from("<4f",self.raw)

    @property
    def reference_q(self):
        return struct.unpack_from("<4f",self.raw,16)

    @property
    def axis(self):
        return struct.unpack_from("<I",self.raw,40)[0]

    @property
    def reference_axis(self):
        return struct.unpack_from("<I",self.raw,44)[0]

    @property
    def limits(self):
        return struct.unpack_from("<2f",self.raw,52)


def validate_descriptors(descriptors):
    require(set(descriptors) == set(RECORDS), "five exact wrist scalar descriptors required")
    for aux,(opcode,offset,hexbytes) in RECORDS.items():
        actual = descriptors[aux]
        require(isinstance(actual,ScalarDescriptor) and actual.opcode == opcode
                and actual.file_offset == offset and actual.raw == bytes.fromhex(hexbytes),
                f"stale or substituted descriptor AUX+{aux:X}")


def load_descriptors(skeleton_data, skeleton=None):
    """Accept unpacked pak bytes, verify whole asset + parsed producer identities."""
    require(hashlib.sha256(skeleton_data).hexdigest() == SKELETON_SHA256,
            "unsupported Nadine skeleton SHA-256")
    parsed = source.load_skeleton(skeleton_data,source.NADINE_SKELETON)
    if skeleton is not None:
        require(skeleton == parsed, "supplied skeleton does not match pinned bytes")
    producers = inputs.scalar_producers(skeleton_data,parsed)
    descriptors = {}
    for aux,(opcode,offset,_) in RECORDS.items():
        p = producers[f"AUX+{aux:X}"]
        require(int(p["descriptor"],16) == offset and p["opcode"] == opcode,
                "scalar producer graph identity")
        descriptors[aux] = ScalarDescriptor(opcode,offset,bytes(skeleton_data[offset:offset+64]))
    validate_descriptors(descriptors)
    return descriptors


def evaluate_weights(local_q26_xyzw, descriptors):
    """Return {AUX offset: float}; Q26 is mandatory and has no actual-pose default."""
    validate_descriptors(descriptors)
    q = quaternion(local_q26_xyzw)
    d = descriptors[0x400]
    result = {0x400:signed_twist_degrees(q,d.target_q,d.axis)}
    for aux in (0x3E4,0x3EC,0x404,0x408):
        d = descriptors[aux]
        result[aux] = angular_weight(q,d.target_q,d.axis,*d.limits,
                                    reference_q=d.reference_q,reference_axis=d.reference_axis,
                                    optional_degrees=result[0x400])
    return result


def verify_native_image(image):
    """Read/hash bytes only; Image is pe_disassemble_va.Image, never MappedImage."""
    require(hashlib.sha256(image.data).hexdigest() == EXE_SHA256, "retail executable SHA-256")
    for address,(size,digest) in FUNCTIONS.items():
        require(hashlib.sha256(image.read(address,size)).hexdigest() == digest,
                f"native scalar worker hash {address:X}")
    require(struct.unpack("<2Q",image.read(0x143026CB0,16)) == (0x141A97060,0x141A951F0),
            "custom scalar dispatch slots")


