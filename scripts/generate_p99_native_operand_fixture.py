#!/usr/bin/env python3
"""Render the reviewed AGZ conditional operand oracle, never run native/game code.

Input is the isolated full-chain input, not a snapshot read from a live game.
Generation fails closed on the exact reviewed size/SHA; it never refreshes the
baseline from whichever file happened to be supplied.
"""
from __future__ import annotations
import argparse
from pathlib import Path

import p99_native_retarget_audit as audit

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "reports" / "p99-full-chain-agz-final.full-input.bin"
DEFAULT_OUTPUT = ROOT / "scanner" / "src" / "nadine_p99_native_operand_fixture.h"


def render(data: bytes) -> str:
    if len(data) != 3948 or audit.source.sha256(data) != audit.EXPECTED_FULL_INPUT_SHA256:
        raise ValueError("not the reviewed AGZ conditional full-chain operand fixture")
    lines = ["#pragma once", "// Generated by scripts/generate_p99_native_operand_fixture.py; do not hand-edit.",
             "// CONDITIONAL null-profile oracle, NOT proof of live profile absence.",
             "// Runtime must compare owned values; never substitute these for borrowed inputs.",
             "#include <array>", "#include <cstdint>", "", "namespace coop::p99_native_operand_fixture {",
             f'inline constexpr char kInputSha256[] = "{audit.EXPECTED_FULL_INPUT_SHA256}";',
             "// Each row: record20[46], record157[46], ChloeRef[48], NadineRef[48].",
             "inline constexpr std::array<std::array<std::uint8_t, 188>, 21> kRows{{"]
    for row in range(21):
        lines.append(f"    {{{{ // semantic row {row}")
        chunk = data[row * 188:(row + 1) * 188]
        for start in range(0, len(chunk), 16):
            lines.append("        " + ", ".join(f"0x{value:02X}" for value in chunk[start:start + 16]) + ",")
        lines.append("    }},")
    lines.extend(["}};", "} // namespace coop::p99_native_operand_fixture", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(args.input.read_bytes())
    if args.check:
        if args.output.read_text(encoding="utf-8") != expected:
            raise ValueError("generated native operand fixture differs")
    else:
        args.output.write_text(expected, encoding="utf-8")
    print(f"AGZ conditional fixture: 3948 bytes, SHA256 {audit.EXPECTED_FULL_INPUT_SHA256}; check={args.check}")


if __name__ == "__main__":
    main()
