#!/usr/bin/env python3
"""Emit the exact relocation-free C39 group0/group1 cmd16 byte contract.

No game/IDA access or file writes. --check compares the checked-in header;
--emit writes generated C++ to stdout for an explicit apply_patch update.
The complete declared program blocks pin source operands, coefficients and
indirect tables as well as the destinations audited by p99_group_program_audit.
"""

from __future__ import annotations

import argparse
from contextlib import redirect_stdout
import io
from pathlib import Path
import struct

import generate_p99_chloe_source_rows as source
import p99_group_program_audit as audit

OUTPUT = source.ROOT / "scanner/src/nadine_p99_group_program_manifest.h"
REGIONS = (
    ("Header", 0x0000, 0x0040),
    ("GroupDescriptors", 0x0040, 0x0100),
    ("ProcessingDescriptors", 0x0140, 0x0050),
    ("ScalarMaps", 0x0190, 0x01A0),
    ("ProgramDirectory", 0x0330, 0x0058),
    ("Group0Program", 0x53E0, 0x39B0),
    ("Group1Program", 0x8D90, 0x01B0),
)
# Retail tll.exe 1.4.21058.0; native dispatch slots read using IDA MCP.
# Opcode133 is not consumed by these programs but pins the sixth custom slot.
BINDINGS = (
    (40, 0x2194470), (41, 0x2194680), (44, 0x21946D0),
    (47, 0x2194720), (49, 0x2194880), (50, 0x2194940),
    (51, 0x21949E0), (52, 0x2194AB0), (53, 0x2194B10),
    (54, 0x2194C30), (128, 0x1A97060), (129, 0x1A951F0),
    (130, 0x1A945F0), (131, 0x1A94D80), (132, 0x1A95E80),
    (133, 0x1A97970),
)

PREAMBLE = r'''#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <limits>
#include <span>

// Generated by scripts/generate_p99_group_program_manifest.py. STATIC only.
// Source: nadine-dlc-base.pak SHA256
// 2bf66e61fae156a41952d8d2659e06215dbe8f0c827a9f6a89cada0c9490b06b.
// Raw skeleton starts at PAK+0x53FE0. Every offset below is RAW-relative.
// None of these regions contains a PAK pointer-fixup field. The program blocks
// include their opcode terminators, padding, all indirect operand tables and
// coefficients. Directory u16+2 sizes are independently checked against the
// final op54/op53 data-table ends and the following program offsets.
//
// This API checks ONLY supplied values; it never reads a live pointer. The
// caller must obtain each exact region from ONE live, identified C39 skeleton,
// keep that skeleton/code/table lifetime valid, and prove group buffers, owner,
// command suffix and job scope independently. Success is NOT a runtime GO.
// Binding checks identify function entrypoints; they do not prove that their
// code bytes are unmodified. The caller owns executable/build integrity.
namespace coop::p99_group_program_manifest {

inline constexpr std::uint32_t kSkeletonId = 0xC39CA709u;
inline constexpr std::uint32_t kRawFileOffset = 0x53FE0u;
inline constexpr std::uint32_t kRawDeclaredEnd = 0x379C0u;
inline constexpr std::uint32_t kRequiredRawExtent = 0x8F40u;
inline constexpr std::uintptr_t kBuiltinTableRva = 0x3026D20u;
inline constexpr std::uintptr_t kCustomTableRva = 0x3026CB0u;
inline constexpr std::uintptr_t kCustomCountRva = 0x300C938u;
inline constexpr std::size_t kBuiltinSnapshotEntries = 55;
inline constexpr std::uint16_t kCustomCount = 6;

enum class Region : std::uint8_t {
    kHeader, kGroupDescriptors, kProcessingDescriptors, kScalarMaps,
    kProgramDirectory, kGroup0Program, kGroup1Program,
};
struct RegionSpec {
    Region id;
    std::uint32_t raw_relative;
    std::uint32_t byte_count;
    std::uint32_t expected_word_first;
};
struct ProgramSpec {
    std::uint8_t group;
    std::uint8_t directory_index;
    std::uint16_t operator_count;
    std::uint32_t raw_relative;
    std::uint32_t byte_count;
    std::uint32_t opcode_bytes; // Includes the zero u16 terminator.
};
struct OperatorSpec {
    std::uint8_t group;
    std::uint8_t ordinal;
    std::uint8_t opcode;
    std::uint8_t payload_words;
    std::uint32_t raw_relative;
    std::array<std::uint16_t, 4> payload;
};
struct BindingSpec {
    std::uint16_t opcode;
    std::uintptr_t handler_rva;
};
'''

POSTAMBLE = r'''
struct RegionView {
    Region id;
    std::uint32_t raw_relative;
    std::span<const std::byte> bytes;
};
struct Bindings {
    std::uintptr_t module_base = 0;
    std::uintptr_t builtin_table_address = 0;
    std::uintptr_t custom_table_address = 0;
    std::uint16_t custom_count = 0;
    // Snapshots of native slots [0,55) and [0,6), respectively. Unconsumed
    // builtin slots are not constrained; all six custom slots are pinned.
    std::span<const std::uintptr_t> builtin_entries;
    std::span<const std::uintptr_t> custom_entries;
};
enum class Reject : std::uint8_t {
    kNone, kRegionCount, kRegionIdentity, kRegionExtent, kRegionBytes,
    kModuleBase, kTableIdentity, kBindingExtent, kCustomCount, kHandler,
};
struct Decision {
    Reject reason = Reject::kNone;
    std::uint32_t detail = 0; // Region ordinal, or mismatched opcode.
    [[nodiscard]] constexpr bool admitted() const noexcept {
        return reason == Reject::kNone;
    }
};

// Exact byte equality, not a collision-prone checksum. Explicit little-endian
// extraction avoids alignment/aliasing requirements on the supplied spans.
[[nodiscard]] inline constexpr Decision validate_regions(
    std::span<const RegionView> regions) noexcept {
    if (regions.size() != kRegions.size()) return {Reject::kRegionCount, 0};
    for (std::size_t i = 0; i < kRegions.size(); ++i) {
        const auto& expected = kRegions[i];
        const auto& actual = regions[i];
        const auto detail = static_cast<std::uint32_t>(i);
        if (actual.id != expected.id || actual.raw_relative != expected.raw_relative)
            return {Reject::kRegionIdentity, detail};
        if (actual.bytes.size() != expected.byte_count)
            return {Reject::kRegionExtent, detail};
        for (std::size_t j = 0; j < actual.bytes.size(); ++j) {
            const auto word = kExpectedWords[expected.expected_word_first + j / 4];
            const auto byte = static_cast<std::uint8_t>(word >> (8 * (j % 4)));
            if (std::to_integer<std::uint8_t>(actual.bytes[j]) != byte)
                return {Reject::kRegionBytes, detail};
        }
    }
    return {};
}

[[nodiscard]] inline constexpr Decision validate_bindings(const Bindings& values) noexcept {
    // Maximum referenced RVA is the builtin table. Reject zero/wraparound
    // before forming ANY module-relative address (including handler entries).
    if (!values.module_base || values.module_base >
        std::numeric_limits<std::uintptr_t>::max() - kBuiltinTableRva)
        return {Reject::kModuleBase, 0};
    if (values.builtin_table_address != values.module_base + kBuiltinTableRva ||
        values.custom_table_address != values.module_base + kCustomTableRva)
        return {Reject::kTableIdentity, 0};
    if (values.builtin_entries.size() != kBuiltinSnapshotEntries ||
        values.custom_entries.size() != kCustomCount)
        return {Reject::kBindingExtent, 0};
    if (values.custom_count != kCustomCount) return {Reject::kCustomCount, 0};
    for (const auto& binding : kBindings) {
        const auto actual = binding.opcode < 128
            ? values.builtin_entries[binding.opcode]
            : values.custom_entries[binding.opcode - 128];
        if (actual != values.module_base + binding.handler_rva)
            return {Reject::kHandler, binding.opcode};
    }
    return {};
}

[[nodiscard]] inline constexpr Decision validate(
    std::span<const RegionView> regions, const Bindings& bindings) noexcept {
    const auto bytes = validate_regions(regions);
    return bytes.admitted() ? validate_bindings(bindings) : bytes;
}

consteval bool manifest_layout_valid() {
    std::size_t next_word = 0;
    std::uint32_t previous_end = 0;
    for (const auto& region : kRegions) {
        if (!region.byte_count || region.byte_count % 4 ||
            region.expected_word_first != next_word ||
            region.raw_relative < previous_end ||
            region.raw_relative > kRequiredRawExtent ||
            region.byte_count > kRequiredRawExtent - region.raw_relative) return false;
        previous_end = region.raw_relative + region.byte_count;
        next_word += region.byte_count / 4;
    }
    if (next_word != kExpectedWords.size()) return false;
    std::array<std::uint16_t, 2> counts{};
    for (const auto& op : kOperators) {
        if (op.group > 1 || op.ordinal != counts[op.group]++ ||
            op.payload_words > op.payload.size()) return false;
        const auto& program = kPrograms[op.group];
        if (op.raw_relative < program.raw_relative ||
            op.raw_relative - program.raw_relative + 2u * (1u + op.payload_words) >
                program.opcode_bytes - 2u) return false;
        bool found = false;
        for (const auto& binding : kBindings) found |= binding.opcode == op.opcode;
        if (!found) return false;
    }
    for (std::size_t i = 0; i < kPrograms.size(); ++i)
        if (counts[i] != kPrograms[i].operator_count) return false;
    for (const auto& binding : kBindings)
        if (binding.handler_rva > kBuiltinTableRva ||
            (binding.opcode < 128 ? binding.opcode >= kBuiltinSnapshotEntries :
                                   binding.opcode - 128 >= kCustomCount)) return false;
    return true;
}
static_assert(manifest_layout_valid());
static_assert(sizeof(std::uintptr_t) == 8);

} // namespace coop::p99_group_program_manifest
'''


def render(asset: Path) -> str:
    data = asset.read_bytes()
    skel = source.load_skeleton(data, source.NADINE_SKELETON)
    raw = skel.spec.raw_offset
    with redirect_stdout(io.StringIO()):
        audit.audit(asset)
    pak = source.PagedPak(data)
    raw_end = raw + audit.u32(data, raw + 0x0C)
    if raw_end != skel.spec.name_data_offset:
        raise ValueError("raw declared end no longer joins name data")
    page, local = pak.page_location(raw)
    if local + raw_end - raw > pak.pages[page].size:
        raise ValueError("raw region leaves its PAK page")
    for (source_page, pointer_local), _targets in pak.fixups.items():
        fixup = pak.pages[source_page].file_offset + pointer_local
        if fixup < raw_end and fixup + 8 > raw:
            raise ValueError("raw skeleton contains a relocatable pointer field")
    if data[raw + 0x17] != 11:
        raise ValueError("program directory count changed")

    parsed = []
    for group in range(2):
        _, relative, length = REGIONS[5 + group]
        flags, declared_size, declared_relative = struct.unpack_from(
            "<HHI", data, raw + 0x330 + 8 * group)
        following = audit.u32(data, raw + 0x330 + 8 * (group + 1) + 4)
        ops = audit.operators(data, raw, relative)
        last = ops[-1]
        # Op54 scalar pairs and op53 vector pairs both have 4-byte records.
        tail_end = last.payload[2] + 4 * last.payload[0]
        if (flags, declared_size, declared_relative, following, tail_end) != (
                0, length, relative, relative + length, length):
            raise ValueError("program block size is not independently closed")
        opcode_bytes = last.relative - relative + 2 + 2 * len(last.payload) + 2
        if any(op.payload[2 if op.opcode != 52 else 3] >= length for op in ops):
            raise ValueError("authored descriptor leaves the declared program")
        parsed.append((relative, length, opcode_bytes, ops))

    lines = [PREAMBLE, "inline constexpr std::array<RegionSpec, 7> kRegions{{"]
    all_words = []
    for name, relative, length in REGIONS:
        lines.append(f"    {{Region::k{name}, 0x{relative:X}u, 0x{length:X}u, {len(all_words)}u}},")
        all_words.extend(struct.unpack_from(f"<{length // 4}I", data, raw + relative))
    lines += ["}};", "", "inline constexpr std::array<ProgramSpec, 2> kPrograms{{"]
    for group, (relative, length, opcode_bytes, ops) in enumerate(parsed):
        lines.append(f"    {{{group}, {group}, {len(ops)}, 0x{relative:X}u, 0x{length:X}u, 0x{opcode_bytes:X}u}},")
    lines += ["}};", "", "inline constexpr std::array<OperatorSpec, 53> kOperators{{"]
    for group, (_, _, _, ops) in enumerate(parsed):
        for op in ops:
            payload = ", ".join(f"0x{x:X}u" for x in op.payload + (0,) * (4-len(op.payload)))
            lines.append(f"    {{{group}, {op.ordinal}, {op.opcode}, {len(op.payload)}, 0x{op.relative:X}u, {{{payload}}}}},")
    lines += ["}};", "", "inline constexpr std::array<BindingSpec, 16> kBindings{{"]
    lines.extend(f"    {{{opcode}, 0x{rva:X}u}}," for opcode, rva in BINDINGS)
    lines += ["}};", "", f"inline constexpr std::array<std::uint32_t, {len(all_words)}> kExpectedWords{{{{"]
    for begin in range(0, len(all_words), 8):
        lines.append("    " + ", ".join(f"0x{word:08X}u" for word in all_words[begin:begin+8]) + ",")
    lines += ["}};", POSTAMBLE]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asset", type=Path,
                        default=source.ROOT / "reports/actor_packages/nadine-dlc-base.pak")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--emit", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render(args.asset)
    if args.emit:
        print(output, end="")
    elif OUTPUT.read_text(encoding="utf-8") != output:
        raise SystemExit("FAIL: generated manifest differs")
    else:
        print("PASS: exact 7-region/53-operator/16-binding manifest; zero raw fixups")


if __name__ == "__main__":
    main()
